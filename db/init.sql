-- ==============================================================
--  Smart Event Hub — PostgreSQL Schema Initialization
--  Runs automatically on first `docker-compose up` via
--  /docker-entrypoint-initdb.d/init.sql
--
--  Database  : eventhub
--  Owner     : eventhub_user
--  Read-only : chatbot_readonly  (used by the AI chatbot agent)
-- ==============================================================

-- --------------------------------------------------------------
-- Extensions
-- --------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm";    -- trigram search on titles/summaries


-- ==============================================================
--  TABLES
-- ==============================================================

-- --------------------------------------------------------------
-- events — Core table storing all extracted/manual events
-- --------------------------------------------------------------
CREATE TABLE IF NOT EXISTS events (
    id            BIGSERIAL PRIMARY KEY,
    user_id       UUID          NOT NULL DEFAULT uuid_generate_v4(),
    source_type   VARCHAR(20)   NOT NULL
                      CHECK (source_type IN ('email','image','pdf','voice','manual','text')),
    source_ref    VARCHAR(255),                         -- e.g. Gmail message ID, filename
    title         VARCHAR(255)  NOT NULL,
    organizer     VARCHAR(150),
    category      VARCHAR(50)   NOT NULL
                      CHECK (category IN ('recruitment','hackathon','workshop','exam','club','class','personal','other')),
    start_time    TIMESTAMPTZ   NOT NULL,
    end_time      TIMESTAMPTZ,
    venue         TEXT,
    summary       TEXT          NOT NULL,
    is_hidden     BOOLEAN       DEFAULT FALSE,
    created_at    TIMESTAMPTZ   DEFAULT NOW()
);

COMMENT ON TABLE  events IS 'All events ingested or created manually by users.';
COMMENT ON COLUMN events.source_type IS 'Channel through which the event was detected.';
COMMENT ON COLUMN events.source_ref  IS 'External reference (Gmail ID, uploaded filename, etc.).';
COMMENT ON COLUMN events.is_hidden   IS 'Soft-delete / hide flag set by user filter rules.';


-- --------------------------------------------------------------
-- user_filter_rules — Natural-language rules that auto-hide events
-- --------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_filter_rules (
    id                SERIAL PRIMARY KEY,
    user_id           UUID         NOT NULL DEFAULT uuid_generate_v4(),
    instruction_text  TEXT         NOT NULL,    -- e.g. "Hide all recruitment events"
    target_category   VARCHAR(50),              -- optional quick filter by category
    created_at        TIMESTAMPTZ  DEFAULT NOW()
);

COMMENT ON TABLE  user_filter_rules IS 'User-defined natural-language rules processed by the AI to auto-hide irrelevant events.';


-- --------------------------------------------------------------
-- chat_history — Persistent chatbot conversation log
-- --------------------------------------------------------------
CREATE TABLE IF NOT EXISTS chat_history (
    id             BIGSERIAL    PRIMARY KEY,
    user_id        UUID         NOT NULL DEFAULT uuid_generate_v4(),
    role           VARCHAR(10)  NOT NULL CHECK (role IN ('user','assistant')),
    message        TEXT         NOT NULL,
    generated_sql  TEXT,                        -- SQL generated by the text-to-SQL agent (for audit)
    created_at     TIMESTAMPTZ  DEFAULT NOW()
);

COMMENT ON TABLE  chat_history IS 'Full conversation history for the AI chatbot, including any generated SQL queries for transparency.';
COMMENT ON COLUMN chat_history.generated_sql IS 'SQL produced by the text-to-SQL step, stored for debugging and audit.';


-- ==============================================================
--  INDEXES
-- ==============================================================

-- events
CREATE INDEX IF NOT EXISTS idx_events_user_id     ON events(user_id);
CREATE INDEX IF NOT EXISTS idx_events_start_time  ON events(start_time);
CREATE INDEX IF NOT EXISTS idx_events_category    ON events(category);
CREATE INDEX IF NOT EXISTS idx_events_is_hidden   ON events(is_hidden);
CREATE INDEX IF NOT EXISTS idx_events_source_type ON events(source_type);

-- Full-text / trigram search on title and summary
CREATE INDEX IF NOT EXISTS idx_events_title_trgm   ON events USING GIN (title   gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_events_summary_trgm ON events USING GIN (summary gin_trgm_ops);

-- chat_history
CREATE INDEX IF NOT EXISTS idx_chat_history_user_id    ON chat_history(user_id);
CREATE INDEX IF NOT EXISTS idx_chat_history_created_at ON chat_history(created_at);

-- user_filter_rules
CREATE INDEX IF NOT EXISTS idx_filter_rules_user_id ON user_filter_rules(user_id);


-- ==============================================================
--  READ-ONLY ROLE (chatbot_readonly)
--  The AI chatbot executes SELECT-only queries through this role.
-- ==============================================================

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT FROM pg_catalog.pg_roles WHERE rolname = 'chatbot_readonly'
    ) THEN
        CREATE ROLE chatbot_readonly WITH LOGIN PASSWORD 'readonly_pass';
    END IF;
END
$$;

GRANT CONNECT                          ON DATABASE eventhub TO chatbot_readonly;
GRANT USAGE                            ON SCHEMA public     TO chatbot_readonly;
GRANT SELECT ON ALL TABLES IN SCHEMA public                 TO chatbot_readonly;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT ON TABLES TO chatbot_readonly;

-- Prevent the read-only role from modifying sequences
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM chatbot_readonly;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    REVOKE ALL ON SEQUENCES FROM chatbot_readonly;


